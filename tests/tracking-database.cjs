// Run after: npm install --prefix tmp/tracking-validation --no-save @electric-sql/pglite
const { PGlite } = require('../tmp/tracking-validation/node_modules/@electric-sql/pglite');
const fs = require('node:fs');
const assert = require('node:assert/strict');
(async () => {
  const db = new PGlite();
  await db.exec(`create role anon; create role authenticated; create schema auth;
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    grant usage on schema public,auth to authenticated,anon;
    create table profiles(id uuid primary key,name text,role text,latitude float8,longitude float8,last_seen timestamptz);
    create table attendance(id uuid default gen_random_uuid(),staff_id text,type text,status text,created_at timestamptz default now());
    create function is_admin_user() returns boolean language sql stable security definer set search_path=public as $$select exists(select 1 from profiles where id=auth.uid() and role='admin')$$;
    create publication supabase_realtime;`);
  await db.exec(fs.readFileSync('supabase/migrations/20260908120000_live_employee_tracking.sql', 'utf8'));
  const employee = '00000000-0000-0000-0000-000000000001';
  const other = '00000000-0000-0000-0000-000000000002';
  const admin = '00000000-0000-0000-0000-000000000003';
  await db.query("insert into profiles values($1,'Employee','employee',null,null,null),($2,'Other','employee',null,null,null),($3,'Admin','admin',null,null,null)", [employee, other, admin]);
  await db.query("insert into attendance(staff_id,type,status,created_at) values($1,'check_in','approved',now()-interval '1 hour')", [employee]);
  const login = async id => { await db.exec('reset role'); await db.query("select set_config('request.jwt.claim.sub',$1,false)", [id]); await db.exec('set role authenticated'); };
  await login(employee);
  const time = Date.now() - 60000;
  const base = { employee_id: employee, latitude: 47.91891, longitude: 106.91842, accuracy: 4, speed: 2, heading: 86, battery: 68, timestamp: time };
  const ingest = async p => (await db.query('select ingest_employee_location($1::jsonb) as result', [JSON.stringify(p)])).rows[0].result;
  assert.equal(await ingest(base), 'accepted');
  assert.equal(await ingest(base), 'accepted');
  assert.equal((await db.query('select * from current_locations')).rows.length, 0, 'employee cannot read admin map');
  await assert.rejects(db.query('insert into current_locations(employee_id,latitude,longitude,timestamp) values($1,0,0,1)', [employee]), /permission denied/);
  await assert.rejects(ingest({ ...base, employee_id: other }), /insufficient_privilege|permission denied/i);
  await assert.rejects(db.query('select ingest_employee_locations($1::jsonb)', [JSON.stringify([{ ...base, timestamp: time+1000 }, { ...base, employee_id: other }])]), /insufficient_privilege|permission denied/i);
  await assert.rejects(db.query('select ingest_employee_locations($1::jsonb)', [JSON.stringify(Array(101).fill(base))]), /Maximum 100/);
  assert.equal(await ingest({ ...base, latitude: 49, timestamp: time+5000 }), 'implausible');
  assert.equal(await ingest({ ...base, accuracy: 300 }), 'invalid');
  assert.equal(await ingest({ ...base, timestamp: Date.now()+90000 }), 'expired');
  assert.equal(await ingest({ ...base, latitude: base.latitude+0.00001, timestamp: time+5000 }), 'accepted');
  assert.equal(await ingest({ ...base, latitude: base.latitude+0.001, timestamp: time+20000 }), 'accepted');
  assert.equal(await ingest({ ...base, latitude: base.latitude+0.0005, timestamp: time+10000 }), 'accepted');
  await login(admin);
  const current = (await db.query('select * from current_locations')).rows[0];
  assert.equal(Number(current.timestamp), time+20000, 'late history must not rewind current');
  assert.equal((await db.query('select * from location_history')).rows.length, 3, 'duplicate and jitter excluded');
  await login(other);
  assert.equal(await ingest({ ...base, employee_id: other }), 'outside-session');
  assert.equal((await db.query('select * from location_history')).rows.length, 0);
  await db.exec('reset role');
  await db.query("insert into attendance(staff_id,type,status,created_at) values($1,'check_out','approved',now()-interval '10 seconds')", [employee]);
  await login(employee);
  assert.equal(await ingest({ ...base, timestamp: Date.now() }), 'outside-session');
  // A queued point captured before checkout is accepted without bringing the employee online.
  assert.equal(await ingest({ ...base, latitude: base.latitude+0.0015, timestamp: time+30000 }), 'accepted');
  await login(admin);
  assert.equal((await db.query('select online from current_locations')).rows[0].online, false);
  await db.exec('reset role; set role anon');
  await assert.rejects(db.query('select * from current_locations'), /permission denied/);
  await assert.rejects(ingest(base), /permission denied/);
  await db.close();
  console.log('PASS: migration, authentication, RLS, own-only sender, monotonic current, duplicate/jitter/jump filters, session start/end and offline replay.');
})().catch(error => { console.error(error); process.exitCode = 1; });
