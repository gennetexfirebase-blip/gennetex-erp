-- ---------------------------------------------------------------------------
-- Хангамжийн размер
-- ---------------------------------------------------------------------------
--
-- Хангамжид хувцас, гутал ордог бөгөөд эдгээр нь размертай:
--   хувцас  — S, M, L, XL, XXL, 3XL
--   гутал   — 39 ... 46
--
-- ЯАГААД ТУСДАА ХҮСНЭГТ БИШ, БАГАНА ВЭ:
--   Размер бүр өөрийн үлдэгдэлтэй байх ёстой — XL 15ш, XXL 5ш гэх мэт.
--   Ажилтанд XL олгоход зөвхөн XL-ийн тоо хасагдана.
--
--   Хэрэв размерыг тусдаа хүснэгтэд гаргавал `stock_movements` нь
--   `inventory.id` руу заадаг тул олголтын бүх урсгалыг дахин бичих
--   шаардлагатай болно. Харин размер бүрийг ТУСДАА МӨР болговол
--   одоо байгаа олгох/хасах систем ямар ч өөрчлөлтгүйгээр ажиллана.
--
--   Жагсаалтад нэрээр нь бүлэглэж, доор нь размеруудыг харуулна:
--
--     Ажлын хантааз          нийт 30ш
--       ├── L    10ш
--       ├── XL   15ш
--       └── XXL   5ш
--
-- `size_group` нь бүлэглэхэд ашиглагдана. Нэр нь адилхан ч өөр бараа
-- байж болох тул зөвхөн нэрээр бүлэглэхэд найдвартай биш.
-- ---------------------------------------------------------------------------

alter table public.inventory
  add column if not exists size text,
  add column if not exists size_group text;

-- Нэг барааны нэг размер зөвхөн НЭГ мөр байна. Давхардвал үлдэгдэл
-- хоёр тийш хуваагдаж, аль нь зөв нь мэдэгдэхгүй болно.
create unique index if not exists inventory_size_group_size_uniq
  on public.inventory (size_group, size)
  where size_group is not null and size is not null;

-- Бүлгээр хайхад хурдан байх
create index if not exists inventory_size_group_idx
  on public.inventory (size_group)
  where size_group is not null;

comment on column public.inventory.size is
  'Размер: хувцас S/M/L/XL/XXL/3XL, гутал 39-46. Размергүй бараанд NULL.';
comment on column public.inventory.size_group is
  'Нэг бараанд харьяалагдах размеруудыг холбоно. Размергүй бараанд NULL.';
