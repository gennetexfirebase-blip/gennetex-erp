export function contractFilename(c: Contract) {
  return `Geree_${c.contract_number}_${(c.given_name || 'ajiltan').replace(/[\\/:*?"<>|\s]+/g, '_')}.pdf`;
}

export async function contractPdfBlob(c: Contract, images: ContractImages = {}) {
  const pdf = await buildContract(c, images);
  return pdf.getBlob();
}

export async function downloadContractPdf(c: Contract, images: ContractImages = {}) {
  const pdf = await buildContract(c, images);
  pdf.download(contractFilename(c));
}
