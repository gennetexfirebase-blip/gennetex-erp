function dateParts(value: string) {
  const d = new Date(`${(value || '').slice(0, 10)}T00:00:00`);
  if (Number.isNaN(d.getTime())) return { y: '____', m: '__', d: '__', iso: value };
  return { y: String(d.getFullYear()), m: String(d.getMonth() + 1), d: String(d.getDate()), iso: value.slice(0, 10) };
}

